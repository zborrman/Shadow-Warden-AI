"use client";
import { useQuery } from "@tanstack/react-query";
import { LivePage, Panel, Kpi, Pill, RecordsTable } from "@/components/ui/live";
import { DataUnavailable } from "@/components/ui/data-unavailable";
import { liveGet, rowsOf, fmtDate } from "@/lib/live";

export default function EvolutionPage() {
  const q = useQuery({
    queryKey: ["/rules"],
    queryFn: () => liveGet<unknown>("/rules", { limit: 200 }),
    retry: false,
  });
  const rows = rowsOf(q.data, "rules");
  const count = (s: string) => rows.filter(r => r.status === s).length;

  return (
    <LivePage title="Evolution Log" subtitle="Detection rules generated by the Evolution Engine, from the rule ledger">
      {q.isError ? (
        <DataUnavailable what="Rule ledger" />
      ) : (
        <>
          <div className="grid grid-cols-2 lg:grid-cols-4 gap-3">
            <Kpi label="Rules in ledger" value={q.isLoading ? "…" : rows.length} />
            <Kpi label="Pending review" value={q.isLoading ? "…" : count("pending_review")} />
            <Kpi label="Active" value={q.isLoading ? "…" : count("active")} />
            <Kpi label="Retired" value={q.isLoading ? "…" : count("retired")} />
          </div>
          <Panel title="Log">
            <RecordsTable
              empty="The Evolution Engine has not generated any rule yet."
              rows={rows}
              cols={[
                { key: "created_at", label: "Created", render: r => fmtDate(r.created_at) },
                { key: "rule_id", label: "Rule", mono: true },
                { key: "rule_type", label: "Kind" },
                { key: "source", label: "Source" },
                { key: "activation_count", label: "Fired", mono: true },
                { key: "fp_reports", label: "FP reports", mono: true },
                { key: "status", label: "Status", render: r => <Pill value={r.status} /> },
              ]}
            />
          </Panel>
        </>
      )}
      <p className="text-[11px] text-gray-500">
        With RULE_REVIEW_MODE=manual a new rule waits in pending_review until an operator approves it;
        false-positive reports can retire it.
      </p>
    </LivePage>
  );
}
